#!/usr/bin/env node
// Build lib/client.cjs from lib/core.js + src/client.js.
//
// The client module system concatenates each package's client bytes as-is and
// expects the file to register itself, so the shared helpers must be inlined
// rather than imported: the page's `require` resolves package names and
// platform seed words (react, the UI primitives), never a relative path. This
// script performs that inlining and nothing else, which keeps the artifact
// reproducible and lets `--check` prove it is current.
//
//   node scripts/build.mjs            write lib/client.cjs
//   node scripts/build.mjs --check    exit 1 when the artifact is stale

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const CORE = join(PACKAGE_ROOT, 'lib/core.js')
const CLIENT = join(PACKAGE_ROOT, 'src/client.js')
const OUT = join(PACKAGE_ROOT, 'lib/client.cjs')

/**
 * Every relative import the browser bundle must satisfy from its own body.
 *
 * The bundle has no module table for relative paths, so an import of a file that
 * is not inlined does not fail loudly — the name simply arrives as `undefined`
 * and the page misbehaves at runtime. Checking it here turns that into a build
 * error, which is the only place it can be seen.
 */
const INLINED = new Set(['../lib/core.js'])

/**
 * Drop ESM syntax so a module body can sit inside a CJS factory unchanged.
 * @param source - one authored module.
 * @returns the same body with imports removed and exports unmarked.
 */
function stripModuleSyntax(source) {
  return source
    .replace(/^import\s[\s\S]*?from\s+'[^']*'[ \t]*\r?\n/gmu, '')
    .replace(/^export\s+(?=(?:const|let|function|class|async)\b)/gmu, '')
    .replace(/^export\s*\{[^}]*\}\s*;?[ \t]*\r?\n?/gmu, '')
}

/**
 * Indent a body so the generated factory reads as one unit.
 * @param source - the module body to nest.
 * @returns the indented body, blank lines left blank.
 */
function indent(source) {
  return source.replace(/\n+$/u, '').split('\n').map((line) => (line === '' ? '' : `    ${line}`)).join('\n')
}

/** @returns the exact bytes `lib/client.cjs` must contain. */
function build() {
  const packageName = JSON.parse(readFileSync(join(PACKAGE_ROOT, 'package.json'), 'utf8')).name
  const clientSource = readFileSync(CLIENT, 'utf8')
  const unresolved = [...clientSource.matchAll(/from\s+'(\.[^']*)'/g)]
    .map((match) => match[1])
    .filter((specifier) => !INLINED.has(specifier))
  if (unresolved.length > 0) {
    // The browser bundle cannot resolve a relative path, so this would ship a
    // page whose imports are silently undefined.
    throw new Error(
      `build: src/client.js imports ${unresolved.join(', ')}, which is not inlined into lib/client.cjs. `
      + 'Add the module to the inlined set, or move what the page needs into lib/core.js.',
    )
  }
  const core = stripModuleSyntax(readFileSync(CORE, 'utf8'))
  const client = stripModuleSyntax(clientSource)
  return [
    '// @generated by scripts/build.mjs — do not edit by hand.',
    '// dsh-connect-opencode-free · browser half (Settings page).',
    '//',
    '// Built from lib/core.js + src/client.js. Run `npm run build` after editing',
    '// either, and `npm run verify` to prove this file is current.',
    "window.__ModuleLoader__.load({",
    `  id: '${packageName}',`,
    '  factory: function (require, module) {',
    "'use strict'",
    '',
    indent(core),
    '',
    indent(client),
    '',
    'const __exports__ = { name: name, inject: inject, apply: apply };',
    'if (module) { module.exports = __exports__; }',
    'return __exports__;',
    '  }',
    '});',
    '',
  ].join('\n')
}

const output = build()
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    console.error('build: lib/client.cjs is missing; run `npm run build`')
    process.exit(1)
  }
  if (current !== output) {
    console.error('build: lib/client.cjs is stale; run `npm run build`')
    process.exit(1)
  }
  console.log('build: lib/client.cjs is current')
} else {
  writeFileSync(OUT, output, 'utf8')
  console.log(`build: wrote ${OUT}`)
}
